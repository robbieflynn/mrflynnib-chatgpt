const pause = () => new Promise(resolve => setTimeout(resolve, 0));
for (const [course, topics] of Object.entries(source.courses)) {
  const slug = course.toLowerCase().replace(' ', '-');
  const doc = new JSDOM(readFileSync(`public/question-bank/formula-booklets/${slug}.html`, 'utf8')).window.document;
  assert.equal(doc.body.dataset.formulaBooklet, course);
  assert.equal(doc.querySelectorAll('main > section').length, 5);
  assert.deepEqual([...doc.querySelectorAll('.group h3')].map(x => x.textContent), topics.flatMap(gs => gs.map(g => g.section + (g.section === 'Prior learning' ? ' – ' + course.slice(-2) : ''))));
  assert.equal(doc.querySelectorAll('.katex-error').length, 0);
  assert.ok(!doc.body.textContent.includes('converges'), 'no added convergence hints');
}
