import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const ts = require("typescript");
const React = require("react");
const { JSDOM } = require("jsdom");
const dom = new JSDOM('<div id="root"></div>', { url: "https://example.test" });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, FormData: dom.window.FormData, IS_REACT_ACT_ENVIRONMENT: true });
const { createRoot } = require("react-dom/client");
let calls = 0, submitted, finish;
const mockAction = async (_state, data) => { calls++; submitted = data; return new Promise(resolve => { finish = resolve; }); };
const source = ts.transpileModule(fs.readFileSync("src/components/admin-course-form.tsx","utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
vm.runInNewContext(source, { exports, window:dom.window, FormData:dom.window.FormData, require: name =>
  name === "@/app/teacher/student-course-actions" ? { changeStudentCourse: mockAction } :
  name === "@/lib/platform-products" ? { productsForCurriculum: () => ["aa-hl","aa-sl","ai-hl","ai-sl"].map(id => ({id,shortTitle:id.toUpperCase().replace("-"," ")})) } : require(name) });
const root = createRoot(document.getElementById("root"));
await React.act(async () => root.render(React.createElement(exports.AdminCourseForm, { accountId:"test-student",currentCourse:"aa-hl",name:"Test Student" })));
const select = document.querySelector("select"), button = document.querySelector("button");
assert.equal(select.value,"aa-hl");
assert.equal(select.options.length,4);
select.value = "aa-sl";
await React.act(async () => select.dispatchEvent(new window.Event("change", { bubbles:true })));
window.confirm = () => false;
await React.act(async () => button.click());
assert.equal(calls,0,"cancel does not submit");
window.confirm = () => true;
await React.act(async () => button.click());
assert.equal(calls,1);
assert.equal(submitted.get("courseId"),"aa-sl");
assert.equal(submitted.get("expectedCourse"),"aa-hl");
assert(button.disabled && select.disabled,"pending prevents duplicate changes");
await React.act(async () => finish({error:"This student's course changed. Reload before trying again."}));
assert.equal(select.value,"aa-sl","failed save retains selection");
assert(document.querySelector('[role="alert"]').textContent.includes("Reload"));
assert(!button.disabled);
await React.act(async () => root.unmount());
dom.window.close();
console.log("PASS: actual React course form choices, confirmation cancellation, submitted IDs, pending controls, stale-form feedback and retry state.");
