import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const code = ts.transpileModule(readFileSync('src/lib/platform-access.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { courseAccessStatuses: status } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const now = new Date('2026-11-12T12:00:00Z');
const grant = (product_code, expires_at, extra = {}) => ({ product_code, status: 'active', starts_at: '2026-01-01T00:00:00Z', expires_at, ...extra });
const date = '2028-09-16T07:22:02Z';
const read = (rows, role = 'student', curriculum = 'ib', seats = []) => status(rows, seats, curriculum, role, now);
assert.deepEqual(read([]), []);
assert.equal(read([grant('course_ib_aa_hl', date)])[0].detail, 'Ends 16 Sept 2028, 11:22 Dubai time');
const two = read([grant('course_ib_aa_hl', date), grant('course_ib_ai_sl', '2028-08-21T07:00:00Z')]);
assert.equal(two.length, 2); assert.notEqual(two[0].detail, two[1].detail);
assert.equal(read([grant('teacher_plus_ib', date)], 'teacher')[0].label, 'All four IB courses');
assert.deepEqual(read([grant('teacher_plus_ib', date)], 'student'), []);
assert.equal(read([grant('student_all_courses_ib', date)])[0].label, 'All four IB courses');
const overlap = read([grant('course_ib_aa_hl', '2027-01-01T00:00:00Z'), grant('teacher_plus_ib', date)], 'teacher');
assert.equal(overlap.length, 1); assert.equal(overlap[0].label, 'All four IB courses');
assert.equal(read([grant('course_ib_aa_hl', null), grant('course_ib_aa_hl', date)])[0].detail, 'No expiry');
assert.equal(read([grant('course_ib_aa_hl', now.toISOString())])[0].status, 'Expired');
assert.deepEqual(read([grant('course_ib_aa_hl', date, { status: 'revoked' })]), []);
assert.equal(read([grant('course_ib_aa_hl', date, { starts_at: '2027-01-01T00:00:00Z' })])[0].status, 'Upcoming');
assert.deepEqual(read([grant('course_igcse', date)]), []);
assert.equal(read([grant('course_ib_aa_hl', date), grant('course_igcse', date)], 'student', 'igcse').length, 1);
const seat = { revoked_at: null, organization_licenses: { product_code: 'course_ib_aa_sl', status: 'pilot', starts_at: '2026-01-01T00:00:00Z', ends_at: date } };
assert.equal(read([], 'student', 'ib', [seat])[0].detail, 'Ends 16 Sept 2028, 11:22 Dubai time');
assert.deepEqual(read([], 'student', 'ib', [{ ...seat, revoked_at: now.toISOString() }]), []);
assert.match(read([], 'admin')[0].detail, /Administrator access/);
console.log('Course access: distinct dates, bundles, overlap, exact expiry, no expiry, revoked, upcoming, school access, role and curriculum checks passed.');
