import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<iframe src="http://localhost/?embedded=1"></iframe>', {url:'http://localhost/question-bank/aa-hl',runScripts:'outside-only',pretendToBeVisual:true});
const host=dom.window, frame=host.document.querySelector('iframe'), child=frame.contentWindow;
child.document.write('<div id="qb-list"><article class="qb-card" data-id="later-question"><div class="qb-body"><p>Later question paragraph</p></div></article></div>');
const rect=(top,height,width=800)=>({top,bottom:top+height,left:0,right:width,width,height});
child.HTMLCanvasElement.prototype.getContext=()=>new Proxy({},{get:()=>()=>{}});
child.matchMedia=()=>({matches:false}); child.CSS={escape:s=>s};
let frames=[]; child.requestAnimationFrame=fn=>(frames.push(fn),frames.length); child.cancelAnimationFrame=()=>{};
const observers=[]; child.ResizeObserver=class {constructor(fn){this.fn=fn;observers.push(this);} observe(){} disconnect(){}};
const flush=()=>{for(let i=0;frames.length&&i<20;i++){const next=frames;frames=[];next.forEach(fn=>fn());} assert.equal(frames.length,0,'layout settles without a resize loop');};
child.HTMLElement.prototype.getBoundingClientRect=()=>rect(0,50);
child.eval(readFileSync('public/question-bank/whiteboard.js','utf8'));
const card=child.document.querySelector('.qb-card'), question=child.document.querySelector('.qb-question-pane'), viewport=child.document.querySelector('.qb-whiteboard-viewport');
const open=child.document.querySelector('.qb-whiteboard-open-button'), action=name=>child.document.querySelector(`[data-whiteboard-action="${name}"]`);
let questionHeight=1800;
question.getBoundingClientRect=()=>rect(10000,questionHeight);
child.document.querySelector('.qb-whiteboard-header').getBoundingClientRect=()=>rect(0,50);
card.getBoundingClientRect=()=>rect(10000,questionHeight+80);
const paragraph=question.querySelector('p');
paragraph.getBoundingClientRect=()=>rect(card.classList.contains('qb-whiteboard-open')?10300:10150,120);
host.scrollY=10200;host.scrollTo=({top})=>{host.scrollY=top;};
frame.getBoundingClientRect=()=>rect(200-host.scrollY,20000);
open.click(); flush();
assert.equal(viewport.style.height,'1748px','board fills a long question below its toolbar');
questionHeight=2400;observers.forEach(o=>o.fn());flush();
assert.equal(viewport.style.height,'2348px','reflow after a split change increases writing height');
questionHeight=900;observers.forEach(o=>o.fn());flush();
assert.equal(viewport.style.height,'848px','board shrinks back without a feedback loop');
host.scrollY=10200;const offset=frame.getBoundingClientRect().top+paragraph.getBoundingClientRect().top;
action('close').click();flush();
assert.equal(frame.getBoundingClientRect().top+paragraph.getBoundingClientRect().top,offset,'closing stays on the same paragraph of a later question');
assert.ok(host.scrollY>9000,'does not return to question one');
open.click();flush();host.scrollY=10200;
action('expand').click();flush();assert.ok(card.style.minHeight,'expanded workspace retains its place in the question list');
host.scrollY=0;action('expand').click();flush();
assert.equal(host.scrollY,10200,'collapse restores the pre-expansion reading position');
assert.equal(card.style.minHeight,'');
child.document.querySelector('[data-whiteboard-layout="below"]').click();flush();
assert.equal(viewport.style.height,'','below layout retains its independent viewport');
child.document.querySelector('[data-whiteboard-layout="side"]').click();flush();
child.innerWidth=390;child.dispatchEvent(new child.Event('resize'));flush();
assert.equal(viewport.style.height,'','stacked mobile layout does not inherit desktop question height');
dom.window.close();
console.log('PASS: question-height reflow, settled sizing, later-question close, expanded return, below and mobile layouts');
