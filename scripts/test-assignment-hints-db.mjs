// Run against an isolated PGlite instance; never connects to the platform database.
// Set HINT_PGLITE_MODULE to the installed @electric-sql/pglite module path.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { PGlite } = await import(process.env.HINT_PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth;
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.user',true),'')::uuid $$;
create table auth.users (id uuid primary key);
create table public.profiles (user_id uuid primary key,role text);
create table public.assignments (id uuid primary key,teacher_id uuid,class_id uuid,status text);
create table public.assignment_questions (assignment_id uuid,question_id text,primary key(assignment_id,question_id));
create table public.assignment_submissions (assignment_id uuid,student_id uuid,status text default 'in_progress',primary key(assignment_id,student_id));
create function public.is_class_member(uuid,uuid) returns boolean language sql as $$ select $2 = '00000000-0000-0000-0000-000000000002'::uuid $$;
create function public.is_assignment_recipient(uuid,uuid) returns boolean language sql as $$ select $2 = '00000000-0000-0000-0000-000000000002'::uuid $$;
create function public.teaches_class(uuid) returns boolean language sql as $$ select auth.uid() = '00000000-0000-0000-0000-000000000001'::uuid $$;
create function public.can_access_assignment(uuid) returns boolean language sql as $$ select auth.uid() in ('00000000-0000-0000-0000-000000000001'::uuid,'00000000-0000-0000-0000-000000000002'::uuid) $$;
grant usage on schema public,auth to authenticated;
grant select on public.assignments to authenticated;
`);
await db.exec(readFileSync('supabase/migrations/20261110_assignment_hints.sql','utf8'));
const teacher='00000000-0000-0000-0000-000000000001', student='00000000-0000-0000-0000-000000000002', stranger='00000000-0000-0000-0000-000000000003', task='00000000-0000-0000-0000-000000000004', cls='00000000-0000-0000-0000-000000000005';
await db.query('insert into auth.users values ($1),($2),($3)',[teacher,student,stranger]);
await db.query("insert into profiles values ($1,'teacher'),($2,'student'),($3,'student')",[teacher,student,stranger]);
await db.query("insert into assignments (id,teacher_id,class_id,status) values ($1,$2,$3,'published')",[task,teacher,cls]);
await db.query("insert into assignment_questions values ($1,'q1')",[task]);
const reveal = (expected, who=student, q='q1') => db.query('select reveal_assignment_hint($1,$2,$3,$4,$5) as steps',[task,who,q,expected,{title:`Step ${expected+1}`}]);
await assert.rejects(reveal(0),/switched off/);
await db.query('update assignments set allow_hints=true where id=$1',[task]);
await assert.rejects(reveal(0,stranger),/not available/);
await assert.rejects(reveal(0,teacher),/not available/);
await assert.rejects(reveal(0,student,'not_assigned'),/not available/);
assert.equal((await reveal(0)).rows[0].steps.length,1);
assert.equal((await reveal(0)).rows[0].steps.length,1,'duplicate request is idempotent');
assert.equal((await reveal(1)).rows[0].steps.length,2);
await assert.rejects(reveal(3),/Reload/);
await db.query("update assignment_submissions set status='submitted' where assignment_id=$1",[task]);
await assert.rejects(reveal(2),/already submitted/);
assert.equal((await reveal(1)).rows[0].steps.length,2,'retry of committed hint survives submission');
const snapshot=await db.query('select hint_count,first_used_at,last_used_at from assignment_hint_usage');
assert.equal(snapshot.rows[0].hint_count,2);assert.ok(snapshot.rows[0].first_used_at);assert.ok(snapshot.rows[0].last_used_at);
await db.exec('set role authenticated');
await db.query("select set_config('test.user',$1,false)",[student]);
assert.equal((await db.query('select * from assignment_hint_usage')).rows.length,1);
await assert.rejects(reveal(2),/permission denied/,'client cannot invoke trusted writer');
await assert.rejects(db.exec('delete from assignment_hint_usage'),/permission denied/);
await db.query("select set_config('test.user',$1,false)",[stranger]);
assert.equal((await db.query('select * from assignment_hint_usage')).rows.length,0,'other student cannot read usage');
await db.query("select set_config('test.user',$1,false)",[teacher]);
assert.equal((await db.query('select * from assignment_hint_usage')).rows.length,1,'owner teacher can read usage');
await db.exec('reset role');
await db.query('update assignments set allow_hints=false where id=$1',[task]);
assert.equal((await db.query('select hint_count from assignment_hint_usage')).rows[0].hint_count,2,'disabling preserves history');
await db.close();
console.log('PASS: migration, opt-in, membership, assigned questions, idempotency, submission lock, history and student/teacher database permissions.');
