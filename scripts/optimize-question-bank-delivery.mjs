import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourceDirectory = resolve(root, "question-bank-data");
const publicDirectory = resolve(root, "public/question-bank/data");

const banks = [
  {
    key: "ib",
    html: resolve(root, "public/question-bank/ib-bank.html"),
    source: resolve(sourceDirectory, "ib-seed.json"),
  },
  {
    key: "igcse",
    html: resolve(root, "public/question-bank/igcse-bank.html"),
    source: resolve(sourceDirectory, "igcse-seed.json"),
  },
];

const startMarker = "  var SEED = [";
const placeholder = `  var SEED = (function(){
    var params = new URLSearchParams(window.location.search);
    var course = params.get('course') || '';
    if(!course){
      try { course = window.localStorage.getItem('qb-course') || ''; } catch(e) { course = ''; }
    }
    course = course || window.__MR_FLYNN_QB_DEFAULT_COURSE__ || '';
    var family = (window.__MR_FLYNN_QB_FAMILIES__ || {})[course] || '';
    return (window.__MR_FLYNN_QB_DATA__ || {})[family] || [];
  })();`;

function checksum(value) {
  return createHash("sha256").update(value).digest("hex").slice(0, 12);
}

function questionBanks(question) {
  return question.banks === undefined ? [question.course] : question.banks;
}

function extractSeed(html) {
  const start = html.indexOf(startMarker);
  if (start < 0) return null;
  const arrayStart = start + "  var SEED = ".length;
  let depth = 0;
  let inString = false;
  let escaped = false;
  let end = -1;
  for (let index = arrayStart; index < html.length; index += 1) {
    const character = html[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === "[") depth += 1;
    else if (character === "]" && --depth === 0) {
      end = index;
      break;
    }
  }
  if (end < 0) throw new Error("Could not find the end of the question-bank seed");
  const json = html.slice(arrayStart, end + 1);
  const suffixStart = html[end + 1] === ";" ? end + 2 : end + 1;
  return {
    questions: JSON.parse(json),
    html: `${html.slice(0, start)}${placeholder}${html.slice(suffixStart)}`,
  };
}

async function readQuestions(bank, html) {
  const extracted = extractSeed(html);
  if (extracted) {
    await mkdir(dirname(bank.source), { recursive: true });
    await writeFile(bank.source, `${JSON.stringify(extracted.questions, null, 2)}\n`);
    return extracted;
  }

  if (!html.includes("  var SEED = ")) {
    throw new Error(`${bank.html} has neither a full seed nor the delivery placeholder`);
  }

  return {
    questions: JSON.parse(await readFile(bank.source, "utf8")),
    html,
  };
}

function assetSource(key, questions) {
  return [
    "window.__MR_FLYNN_QB_DATA__ = window.__MR_FLYNN_QB_DATA__ || {};",
    `window.__MR_FLYNN_QB_DATA__[${JSON.stringify(key)}] = ${JSON.stringify(questions)};`,
    "",
  ].join("\n");
}

async function writeAsset(key, questions, filenameStem = key) {
  const source = assetSource(key, questions);
  const hash = checksum(source);
  const filename = `${filenameStem}.${hash}.js`;
  await mkdir(publicDirectory, { recursive: true });
  await writeFile(resolve(publicDirectory, filename), source);
  return `/question-bank/data/${filename}`;
}

function loaderMarkup({ assets, counts, families, defaultCourse }) {
  return `
<!-- QUESTION_BANK_DATA_LOADER: generated by scripts/optimize-question-bank-delivery.mjs -->
<script>
(function(){
  window.__MR_FLYNN_QB_DATA__ = window.__MR_FLYNN_QB_DATA__ || {};
  window.__MR_FLYNN_QB_ASSETS__ = ${JSON.stringify(assets)};
  window.__MR_FLYNN_QB_COUNTS__ = ${JSON.stringify(counts)};
  window.__MR_FLYNN_QB_FAMILIES__ = ${JSON.stringify(families)};
  window.__MR_FLYNN_QB_DEFAULT_COURSE__ = ${JSON.stringify(defaultCourse)};
  var pending = {};
  function familyFor(course){ return window.__MR_FLYNN_QB_FAMILIES__[course] || ''; }
  window.__MR_FLYNN_QB_LOAD_COURSE__ = function(course){
    var family = familyFor(course);
    if(!family) return Promise.reject(new Error('Unknown question bank: ' + course));
    if(window.__MR_FLYNN_QB_DATA__[family]) return Promise.resolve(window.__MR_FLYNN_QB_DATA__[family]);
    if(pending[family]) return pending[family];
    pending[family] = new Promise(function(resolve, reject){
      var script = document.createElement('script');
      script.src = window.__MR_FLYNN_QB_ASSETS__[family];
      script.async = true;
      script.onload = function(){ resolve(window.__MR_FLYNN_QB_DATA__[family] || []); };
      script.onerror = function(){ reject(new Error('Could not load the selected question bank. Please try again.')); };
      document.head.appendChild(script);
    });
    return pending[family];
  };

  var params = new URLSearchParams(window.location.search);
  var requested = params.get('course') || '';
  if(!requested){
    try { requested = window.localStorage.getItem('qb-course') || ''; } catch(e) { requested = ''; }
  }
  var initialFamily = familyFor(requested || window.__MR_FLYNN_QB_DEFAULT_COURSE__);
  if(initialFamily && window.__MR_FLYNN_QB_ASSETS__[initialFamily]){
    document.write('<script src="' + window.__MR_FLYNN_QB_ASSETS__[initialFamily] + '"><\\/script>');
  }
})();
</script>
`;
}

function stripLoaders(html) {
  return html
    .replace(/\n?<!-- QUESTION_BANK_DATA_LOADER:[^\n]*-->\n?/g, "\n")
    .replace(/\n?<script>\n\(function\(\)\{\n  window\.__MR_FLYNN_QB_DATA__[\s\S]*?\n\}\)\(\);\n<\/script>\n*/g, "\n");
}

function replaceLoader(html, markup) {
  const cleaned = stripLoaders(html);
  const mainScript = "\n<script>\n(function(){";
  const position = cleaned.indexOf(mainScript);
  if (position < 0) throw new Error("Could not find the question-bank application script");
  return `${cleaned.slice(0, position)}\n${markup.trim()}\n${cleaned.slice(position)}`;
}

function removeLoader(html) {
  return stripLoaders(html);
}

function inlineQuestions(html, questions) {
  const seedPlaceholder = /  var SEED = \(function\(\)\{[\s\S]*?\n  \}\)\(\);/;
  if (!seedPlaceholder.test(html)) throw new Error("Could not find the question-bank delivery placeholder");
  return html.replace(seedPlaceholder, `  var SEED = ${JSON.stringify(questions)};`);
}

const manifest = {};

await mkdir(publicDirectory, { recursive: true });
for (const filename of await readdir(publicDirectory)) {
  if (/^(?:ib|igcse)[-.].+\.js$/.test(filename)) {
    await unlink(resolve(publicDirectory, filename));
  }
}

for (const bank of banks) {
  const originalHtml = await readFile(bank.html, "utf8");
  const { questions, html: shell } = await readQuestions(bank, originalHtml);

  if (bank.key === "ib") {
    const definitions = {
      aahl: questions.filter((question) => questionBanks(question).includes("AA HL")),
      aasl: questions.filter((question) => questionBanks(question).includes("AA SL")),
      aihl: questions.filter((question) => questionBanks(question).includes("AI HL")),
      aisl: questions.filter((question) => questionBanks(question).includes("AI SL")),
    };
    const assets = {
      aahl: await writeAsset("aahl", definitions.aahl, "ib-aa-hl"),
      aasl: await writeAsset("aasl", definitions.aasl, "ib-aa-sl"),
      aihl: await writeAsset("aihl", definitions.aihl, "ib-ai-hl"),
      aisl: await writeAsset("aisl", definitions.aisl, "ib-ai-sl"),
    };
    const courses = ["AA HL", "AA SL", "AI HL", "AI SL"];
    const counts = Object.fromEntries(courses.map((course) => [
      course,
      questions.filter((question) => questionBanks(question).includes(course) && !question.offSyllabus && !question.provisional).length,
    ]));
    const families = { "AA HL": "aahl", "AA SL": "aasl", "AI HL": "aihl", "AI SL": "aisl" };
    const loader = loaderMarkup({ assets, counts, families, defaultCourse: "AA HL" });
    await writeFile(bank.html, replaceLoader(shell, loader));
    manifest.ib = { sourceQuestions: questions.length, assets, counts };
  } else {
    const course = "IGCSE Higher";
    const counts = { [course]: questions.filter((question) => !question.offSyllabus && !question.provisional).length };
    // IGCSE has one course and is small enough that a second request would make
    // its first visit slower. Keep it self-contained, but compact the JSON.
    await writeFile(bank.html, inlineQuestions(removeLoader(shell), questions));
    manifest.igcse = { sourceQuestions: questions.length, assets: {}, counts };
  }
}

await writeFile(resolve(publicDirectory, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
